"""Phase 4: applications, custom tasks and workload events.

Adds three tables and one column:

* ``applications`` — a reusable, publishable instance shape plus the
  introduction that explains it. It owns no cluster objects; launching one
  creates an ``instances`` row in the launcher's workspace, so quota, namespace
  and lifecycle stay in exactly one place. ``is_curated`` replaces the plan's
  separate ``app_templates`` table: a template only an administrator may author
  is an application with ``visibility=global`` and ``is_curated=true``, and two
  near-identical tables would drift and force every listing to union them.

* ``tasks`` — one ``batch/v1`` Job. The resource shape is snapshotted for the
  same reason instances snapshot theirs: retiring a spec must not rewrite what a
  finished job actually asked for, and usage accounting needs the real figure.
  ``max_runtime_seconds`` maps to Kubernetes' ``activeDeadlineSeconds`` rather
  than to a sweeper, so a task cannot outlive its limit while the backend is
  down.

* ``workload_events`` — an append-only timeline. Status alone loses history, and
  Kubernetes events expire within the hour and say nothing about who asked for
  what. One (kind, id) pair rather than four nullable foreign keys, so "what
  happened in this workspace today" stays a single indexed query.

* ``resource_group_limits.max_concurrent_tasks`` — tasks consume the same
  namespace quota as instances, so the workspace's task ceiling has to come from
  somewhere. It is a separate number from ``max_concurrent_instances`` because a
  ten-minute job and a day-long interactive session pressure a pool differently.
  Defaulting to 4 keeps existing rows usable rather than silently setting their
  task allowance to zero.

``gpu_type`` stays ``VARCHAR(32)`` on both new tables, matching every other
table: adding an accelerator model must never require a type migration.
"""

