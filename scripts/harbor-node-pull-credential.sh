#!/usr/bin/env bash
#
# Generate the node-level registry credential that lets kubelet pull private
# images without an imagePullSecret on every namespace.
#
# Why this exists
# ---------------
# A Pod only carries pull credentials if `imagePullSecrets` is set on it, or on
# its ServiceAccount. The platform sets neither — its workloads run under the
# namespace's `default` ServiceAccount, which has no secrets attached — so a
# private Harbor project is unreachable: every pull ends in ImagePullBackOff.
#
# kubelet's fallback order is:
#
#   1. the Pod's imagePullSecrets
#   2. its ServiceAccount's imagePullSecrets
#   3. the node's containerd registry configuration   <- this script
#   4. anonymous
#
# This script generates (3). containerd's own documentation is explicit that step
# 3 only applies "when auth config is not specified by Kubernetes via CRI", so a
# per-namespace Secret added later still wins — which is what makes this a
# stepping stone to per-group robots rather than a dead end.
#
# The tradeoff, stated plainly: a node credential is not scoped to a tenant. Any
# Pod on the node can pull from any project the robot can read, so read
# isolation between groups is lost — not on leak, but by construction. Use a
# robot with Pull-only permission, never an account that can push or delete.
#
# The generated block is a credential: it holds the robot's password in plain
# text on every node. Treat the output like a key file.
set -euo pipefail

HARBOR_HOST="${HARBOR_HOST:-}"
ROBOT_USERNAME="${ROBOT_USERNAME:-}"
ROBOT_PASSWORD="${ROBOT_PASSWORD:-}"
CONTAINERD_VERSION="${CONTAINERD_VERSION:-1}"
DRY_RUN="${DRY_RUN:-false}"

if [ -z "$HARBOR_HOST" ]; then
  echo "缺少 HARBOR_HOST，例如 HARBOR_HOST=harbor.example.edu" >&2
  exit 1
fi
if [ -z "$ROBOT_USERNAME" ] || [ -z "$ROBOT_PASSWORD" ]; then
  cat >&2 <<'EOF'
缺少 ROBOT_USERNAME / ROBOT_PASSWORD。

请在 Harbor 的「Administration → Robot Accounts」新建一个**系统级** robot：

  · Cover all projects        ← 勾选（否则新加的组 project 拉不动）
  · 权限只勾 List Repository + Pull Repository
  · 不要勾任何 Push / Delete 权限
  · Expiration 选 Never Expired（默认 30 天，到期后全校拉取会集体失败，
    而且表现为 ImagePullBackOff，很容易误判成网络故障）
EOF
  exit 1
fi

# Harbor strips the scheme from the host it hands back in a reference, and a
# config keyed on `https://harbor.example.edu` would never match the
# `harbor.example.edu/...` that a Pod actually asks for.
HARBOR_HOST="${HARBOR_HOST#*://}"
HARBOR_HOST="${HARBOR_HOST%/}"

if [ "$CONTAINERD_VERSION" = "2" ]; then
  PLUGIN="io.containerd.cri.v1.images"
  FORMAT_VERSION=3
else
  PLUGIN="io.containerd.grpc.v1.cri"
  FORMAT_VERSION=2
fi

BASIC_AUTH="$(printf '%s:%s' "$ROBOT_USERNAME" "$ROBOT_PASSWORD" | base64 | tr -d '\n')"

CONFIG_BLOCK="$(cat <<EOF
# --- kube-wl-ai: node-level pull credential for $HARBOR_HOST ---
# Generated by scripts/harbor-node-pull-credential.sh. Contains a credential.
#
# \`registry.configs.*.auth\` is marked deprecated upstream in favour of
# certs.d/hosts.toml, but the deprecation notice says outright that it "will NOT
# have an equivalent way to store unencrypted secrets in the host configuration
# files" and that it stays supported. It remains the documented way to do this.
version = $FORMAT_VERSION

[plugins."$PLUGIN".registry.configs."$HARBOR_HOST".auth]
  username = "$ROBOT_USERNAME"
  password = "$ROBOT_PASSWORD"
EOF
)"

HOSTS_TOML="$(cat <<EOF
# /etc/containerd/certs.d/$HARBOR_HOST/hosts.toml
#
# The certs.d alternative, for a containerd configured with
#   [plugins."$PLUGIN".registry]
#     config_path = "/etc/containerd/certs.d"
# and no explicit creds in config.toml.
server = "https://$HARBOR_HOST"

[host."https://$HARBOR_HOST"]
  capabilities = ["pull", "resolve"]

  [host."https://$HARBOR_HOST".header]
    authorization = "Basic $BASIC_AUTH"
EOF
)"

if [ "$DRY_RUN" = "true" ]; then
  printf '%s\n\n' "$CONFIG_BLOCK"
  printf '%s\n' "$HOSTS_TOML"
  exit 0
fi

cat <<EOF
把下面这段追加到**每个计算节点**的 /etc/containerd/config.toml：

$CONFIG_BLOCK

如果 config.toml 里已经有同名段落，请合并而不是重复追加——TOML 不允许
同一个键出现两次，containerd 会拒绝启动。

然后重启并验证：

  sudo systemctl restart containerd

  # 命令行验证：能拉到私有 project 里的镜像
  sudo crictl pull $HARBOR_HOST/<组名>/<用户名>/<镜像>:<tag>

  # 集群侧验证：找一台节点，确认 Pod 不再 ImagePullBackOff
  kubectl get events -A --field-selector reason=Failed | grep -i pull

如果需要沿用新版 certs.d 方式（containerd 2.x 的推荐做法），改放这个文件：

$HOSTS_TOML

注意它依赖 config.toml 里已设置 config_path = "/etc/containerd/certs.d"。

────────────────────────────────────────────────────────────────────────
轮换
────────────────────────────────────────────────────────────────────────
节点级凭证的代价就在这里：换一次要动所有节点。

  1. Harbor 里点 robot 的 Refresh Secret，拿到新密码
  2. 逐节点更新 /etc/containerd/config.toml 并 systemctl restart containerd
  3. 重启期间该节点拉新镜像会失败，但已缓存的镜像不受影响

分批做（先拿一个节点试），并在 Harbor 里把旧 robot 停用之前确认新凭证生效。

────────────────────────────────────────────────────────────────────────
安全边界
────────────────────────────────────────────────────────────────────────
· 凭证以明文存在每个节点的 /etc/containerd/config.toml，root 可读。
· 平台的工作负载**不特权**、**没有 hostPath**，所以容器内的用户读不到它。
  但节点的 SSH 用户和任何集群管理员都能读到。
· 它不区分租户：节点上任何 Pod 都能拉该 robot 可读的所有 project。因此
  「组之间互相看不到镜像」这条保证在 registry 层是没有的——可见性只由平台
  的目录（Image.visibility）控制，而那只管页面显示什么。
· 所以权限只给 Pull。给它 Push/Delete 等于把「删光全校镜像」的能力散布到
  每一台运行不可信用户代码的机器上。
EOF
